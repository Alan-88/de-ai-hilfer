// Browser-only fixtures; no model calls or database writes.
async (page) => {
  const check=(value,message)=>{if(!value) throw new Error(message);};
  let calls=[];
  let submissions=[];
  let delays={};
  let failures=new Set();
  await page.route('**/api/v1/suggestions?*',async route=>{
    const url=new URL(route.request().url());
    const q=url.searchParams.get('q');
    calls.push(q);
    await new Promise(resolve=>setTimeout(resolve,delays[q]??30));
    const item={query_text:`word-${q}`,entry_id:1,source:'知识库',suggestion_type:'knowledge_semantic',preview:q,analysis_markdown:'',structured_analysis:null,follow_ups:[]};
    await route.fulfill({status:failures.has(q)?500:200,json:{suggestions:q==='空'?[]:[item]}}).catch(()=>{});
  });
  await page.route('**/api/v1/analyze**',async route=>{
    submissions.push(route.request().postData());
    await route.fulfill({status:500,json:{detail:'test submission intercepted'}});
  });
  await page.goto(`https://de.alan-studio.uk/?lifecycle=${Date.now()}`);
  const input=page.getByRole('textbox',{name:'查询德语单词或中文含义',exact:true});
  await input.fill('甲');
  await page.getByText('word-甲',{exact:true}).waitFor();
  delays['乙']=600;
  failures.add('乙');
  await input.fill('乙');
  await page.waitForTimeout(260);
  await input.fill('甲');
  await page.waitForTimeout(700);
  check(await page.getByText('word-甲',{exact:true}).count()===1,'A→B→A lost cached A');
  check(await page.getByText('候选查询失败，请重试',{exact:true}).count()===0,'Old failure overwrote current A');
  delays['丙']=600;
  await input.fill('丙');
  await page.waitForTimeout(260);
  await input.fill('丁');
  await page.getByText('word-丁',{exact:true}).waitFor();
  await page.waitForTimeout(500);
  check(await page.getByText('word-丙',{exact:true}).count()===0,'Old success replaced newer result');
  delays['戊']=600;
  await input.fill('戊');
  await page.waitForTimeout(260);
  await page.locator('button[title="清空"]').click();
  await page.waitForTimeout(650);
  check(await page.getByText('word-戊',{exact:true}).count()===0,'Clear allowed old result');
  await input.fill('空');
  await page.getByText('暂无候选，请换个说法').waitFor();
  await input.press('Enter');
  await page.waitForTimeout(200);
  check(submissions.length===0,'Empty Chinese initialized original query');
  failures.add('错');
  await input.fill('错');
  await page.getByText('候选查询失败，请重试',{exact:true}).waitFor();
  await input.press('Enter');
  await page.waitForTimeout(300);
  check(submissions.length===0,'Failed Chinese initialized original query');
  failures.delete('错');
  await page.getByText('候选查询失败，请重试',{exact:true}).click();
  await page.getByText('word-错',{exact:true}).waitFor();
  await input.focus();
  await input.press('Tab');
  check(await page.getByPlaceholder('添加线索，例如：关于法律、口语、或者它的近义词...').isVisible(),'Tab association toggle broken');
  await page.getByPlaceholder('添加线索，例如：关于法律、口语、或者它的近义词...').press('Tab');
  delays['闭']=600;
  await input.fill('闭');
  await page.waitForTimeout(260);
  await input.press('Escape');
  await page.waitForTimeout(700);
  check(await page.locator('.integrated-suggestions').count()===0,'Late response reopened dismissed panel');
  delays['新']=700;
  await input.fill('新');
  await page.waitForTimeout(250);
  await input.press('Enter');
  await page.waitForTimeout(1000);
  check(calls.filter(q=>q==='新').length===1,'Submit duplicated in-flight request');
  check(submissions.length===1 && submissions[0].includes('word-新') && !submissions[0].includes('word-错'),'Submit chose stale first candidate');
  if(await page.getByRole('button',{name:'展开搜索',exact:true}).isVisible()) await page.getByRole('button',{name:'展开搜索',exact:true}).click();
  await input.focus();
  failures.add('OriginalWord');
  await input.fill('OriginalWord');
  await page.getByText('候选查询失败，请重试',{exact:true}).waitFor();
  await input.press('Enter');
  await page.waitForTimeout(300);
  check(submissions.some(body=>body?.includes('OriginalWord')),'Lexical failure lost original-query fallback');
  await page.unroute('**/api/v1/suggestions?*');
  await page.unroute('**/api/v1/analyze**');
  return {passed:true,calls,submissions};
}
